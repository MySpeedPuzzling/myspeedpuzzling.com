<?php

declare(strict_types=1);

namespace SpeedPuzzling\Web\Controller\Compete;

use SpeedPuzzling\Web\Exceptions\OnlineLinkNotFound;
use SpeedPuzzling\Web\Query\GetCompetitionParticipants;
use SpeedPuzzling\Web\Security\CompetitionEditVoter;
use SpeedPuzzling\Web\Services\LiveKit\LiveKitSettings;
use SpeedPuzzling\Web\Services\NameTagQrCode;
use SpeedPuzzling\Web\Services\OnlineRounds\OnlineAccess;
use SpeedPuzzling\Web\Services\OnlineRounds\OnlineDetectorAssets;
use SpeedPuzzling\Web\Services\OnlineRounds\OnlineRoundState;
use SpeedPuzzling\Web\Services\RetrieveLoggedUserProfile;
use SpeedPuzzling\Web\Value\InAppBrowser;
use SpeedPuzzling\Web\Value\OnlineAccessContext;
use SpeedPuzzling\Web\Value\OnlineDetectionMode;
use Symfony\Bundle\FrameworkBundle\Controller\AbstractController;
use Symfony\Component\HttpFoundation\Request;
use Symfony\Component\HttpFoundation\Response;
use Symfony\Component\HttpKernel\EventListener\AbstractSessionListener;
use Symfony\Component\Routing\Attribute\Route;
use Symfony\Component\Routing\Exception\RouteNotFoundException;
use Symfony\Component\Routing\Generator\UrlGeneratorInterface;

/**
 * The page a participant's phone opens from their personal link (docs/features/online-competitions/README.md §5.4,
 * §5.5): the countdown, the stopwatch, the Finished button and the camera taking the evidence - one page for the whole
 * round, its screens driven by the round's state in the browser (assets/controllers/compete_controller.js).
 *
 * - The token is the access right: no account, no session (an anonymous visit never starts one), a draft competition's
 *   link works too. An unknown or replaced link gets a friendly 404 page.
 * - The page carries the token: `no-store`, `Referrer-Policy: same-origin` (`no-referrer` would break the stateless
 *   CSRF of the connect POST), `noindex`. So the page may depend on the visitor: the in-app browser notice reads the
 *   User-Agent, a signed-in visitor gets the connect state.
 * - The connect state (README §5.4, the statuses of the `compete_connect` answer): `anonymous` (sign in to keep the
 *   result), `auto` (the page POSTs the connect itself - a GET never writes; also for the player the participant is
 *   connected to while they have not confirmed the link yet - the POST confirms it, ConfirmOnlineLink),
 *   `already_connected`, `belongs_to_other`, `is_other_participant`, `organiser_confirm_required` (a preview: the page
 *   sends nothing until "This is me"). The POST decides for good (OnlineConnectRules) - this is what the page shows
 *   before it.
 * - The QR on a computer ("Continue on your phone") encodes this very page's URL.
 * - Live video (contract phase-1b.md stream VP): with a media server configured (LiveKitSettings) the page carries its
 *   video parts and `video` - the token and studio-answer endpoints, the round's watch page; the round's own switch is
 *   read live from the state, so a round whose video is turned on later needs no reload. Without one the page is the
 *   Phase 1 page, byte for byte. Costs no statement.
 * - Finish detection (Phase 2, stream P2I): when the round's detection is not off, the page carries its detection parts
 *   and `detection` - where the detector's runtime and models come from (OnlineDetectorAssets); the mode itself (on /
 *   shadow, or off again) is read live from the state. A round whose detection is off is the page without them, byte for
 *   byte - turned on later, a page already open stays button-only until it is loaded again. Costs no statement (the
 *   online round is read for the state anyway).
 *
 * The participant API (stream A: `online_time`, `compete_api_*`, `compete_connect`) is generated by route name; until
 * those routes exist the contract's fixed paths stand in (contract §5) and the connect is left out.
 */
final class CompetePageController extends AbstractController
{
    public const string CONNECT_ANONYMOUS = 'anonymous';
    public const string CONNECT_AUTO = 'auto';
    public const string CONNECT_ALREADY_CONNECTED = 'already_connected';
    public const string CONNECT_BELONGS_TO_OTHER = 'belongs_to_other';
    public const string CONNECT_IS_OTHER_PARTICIPANT = 'is_other_participant';
    public const string CONNECT_ORGANISER = 'organiser_confirm_required';

    // The stateless CSRF token id of `compete_connect` (stream A)
    public const string CONNECT_CSRF_TOKEN_ID = 'compete_connect';

    // Stands for the invitation's id in the studio answer's URL (the page puts the real one in its place)
    public const string STUDIO_INVITE_PLACEHOLDER = '00000000-0000-0000-0000-000000000000';

    private const array LOCALES = ['en', 'cs', 'de', 'es', 'fr', 'ja'];

    public function __construct(
        private readonly OnlineAccess $onlineAccess,
        private readonly OnlineRoundState $onlineRoundState,
        private readonly RetrieveLoggedUserProfile $retrieveLoggedUserProfile,
        private readonly GetCompetitionParticipants $getCompetitionParticipants,
        private readonly NameTagQrCode $qrCode,
        private readonly LiveKitSettings $liveKitSettings,
        private readonly OnlineDetectorAssets $onlineDetectorAssets,
    ) {
    }

    #[Route(
        path: [
            'cs' => '/soutezit/{token}',
            'en' => '/en/compete/{token}',
            'es' => '/es/compete/{token}',
            'ja' => '/ja/compete/{token}',
            'fr' => '/fr/compete/{token}',
            'de' => '/de/compete/{token}',
        ],
        name: 'compete_page',
        methods: ['GET'],
    )]
    public function __invoke(Request $request, string $token): Response
    {
        try {
            $context = $this->onlineAccess->forToken($token);
        } catch (OnlineLinkNotFound) {
            // A link that was copied in part, replaced by a new one, or of a removed participant - said kindly
            return self::private($this->render('compete/not_found.html.twig', [], new Response(status: Response::HTTP_NOT_FOUND)));
        }

        $state = $this->onlineRoundState->forParticipant($context);
        $pagePath = $this->generateUrl('compete_page', ['token' => $token]);
        $pageUrl = $this->generateUrl('compete_page', ['token' => $token], UrlGeneratorInterface::ABSOLUTE_URL);
        $connect = $this->connectState($context);

        return self::private($this->render('compete/page.html.twig', [
            'state' => $state,
            'participant' => $context->participant,
            'competition' => $context->competition,
            'round' => $context->round,
            'online_round' => $context->onlineRound,
            'initial_screen' => match (true) {
                $state['round'] === null => 'no_round',
                $state['entry'] === null => 'not_entered',
                default => 'welcome',
            },
            'urls' => $this->apiUrls($token),
            // The template adds the CSRF token - for a signed-in visitor only: an anonymous view touches no token storage
            'connect' => [
                'status' => $connect,
                'url' => in_array($connect, [self::CONNECT_AUTO, self::CONNECT_ORGANISER], true) ? $this->pathOrNull('compete_connect', ['token' => $token]) : null,
                'playerName' => $this->retrieveLoggedUserProfile->getProfile()?->playerName,
            ],
            'login_url' => $this->generateUrl('login', ['return' => $pagePath]),
            'page_url' => $pageUrl,
            'qr_svg' => $this->qrCode->svg($pageUrl),
            'in_app' => InAppBrowser::fromUserAgent($request->headers->get('User-Agent')),
            'results_url' => $this->resultsUrl($context),
            'language_urls' => $this->languageUrls($token),
            'video' => $this->videoConfig($token, $context),
            'detection' => $this->detectionConfig($context),
        ]));
    }

    /**
     * The page's finish detection (README §5.7) - null while the round's detection is off: the page has no detection
     * parts then.
     *
     * @return null|array{assets: array{tasksVisionUrl: string, wasmBaseUrl: string, poseModelUrl: string, gestureModelUrl: string}}
     */
    private function detectionConfig(OnlineAccessContext $context): null|array
    {
        $mode = $context->onlineRound->detectionMode ?? OnlineDetectionMode::Off;

        if ($context->round === null || $mode === OnlineDetectionMode::Off) {
            return null;
        }

        return ['assets' => $this->onlineDetectorAssets->urls()];
    }

    /**
     * The page's live video (contract phase-1b.md stream VP) - null without a media server: the page has no video
     * parts then. The round's own switch ("video", "see each other", "studio") comes with the state, live.
     *
     * @return null|array{urls: array{token: string, studioAnswer: string, watch: null|string}, placeholder: string}
     */
    private function videoConfig(string $token, OnlineAccessContext $context): null|array
    {
        if ($this->liveKitSettings->isAvailable() === false) {
            return null;
        }

        return [
            'urls' => [
                'token' => $this->generateUrl('compete_api_video_token', ['token' => $token]),
                'studioAnswer' => $this->generateUrl('compete_api_studio_answer', ['token' => $token, 'inviteId' => self::STUDIO_INVITE_PLACEHOLDER]),
                // The studio on the spectators' page - a second screen watches it there
                'watch' => $context->round === null ? null : $this->generateUrl('online_watch', ['roundId' => $context->round->id->toString()]),
            ],
            'placeholder' => self::STUDIO_INVITE_PLACEHOLDER,
        ];
    }

    /**
     * What the signed-in visitor's account has to do with this link (README §5.4) - read only, the POST decides.
     */
    private function connectState(OnlineAccessContext $context): string
    {
        $viewer = $this->retrieveLoggedUserProfile->getProfile();

        if ($viewer === null) {
            return self::CONNECT_ANONYMOUS;
        }

        $connectedPlayer = $context->participant->player;

        if ($connectedPlayer !== null) {
            if ($connectedPlayer->id->toString() !== $viewer->playerId) {
                return self::CONNECT_BELONGS_TO_OTHER;
            }

            // Theirs, but not shown to be held by them yet (an organiser connected them): the page POSTs the connect,
            // which confirms the link (ConfirmOnlineLink) - the event page hands the link only to whom confirmed it
            return $context->participant->hasConfirmedOnlineLink() ? self::CONNECT_ALREADY_CONNECTED : self::CONNECT_AUTO;
        }

        $competitionId = $context->competition->id->toString();
        $participantId = $context->participant->id->toString();
        $otherConnections = array_filter(
            $this->getCompetitionParticipants->getPlayerConnections($competitionId, $viewer->playerId),
            static fn (string $connectedId): bool => strtolower($connectedId) !== strtolower($participantId),
        );

        if ($otherConnections !== []) {
            return self::CONNECT_IS_OTHER_PARTICIPANT;
        }

        // An organiser, a maintainer or an admin opening a participant's link looks at it - "This is me" connects
        if ($this->isGranted(CompetitionEditVoter::COMPETITION_EDIT, $competitionId)) {
            return self::CONNECT_ORGANISER;
        }

        return self::CONNECT_AUTO;
    }

    /**
     * @return array{time: string, state: string, heartbeat: string, events: string, media: string}
     */
    private function apiUrls(string $token): array
    {
        return [
            'time' => $this->pathOrNull('online_time', []) ?? '/-/time',
            'state' => $this->pathOrNull('compete_api_state', ['token' => $token]) ?? '/api/compete/' . $token . '/state',
            'heartbeat' => $this->pathOrNull('compete_api_heartbeat', ['token' => $token]) ?? '/api/compete/' . $token . '/heartbeat',
            'events' => $this->pathOrNull('compete_api_events', ['token' => $token]) ?? '/api/compete/' . $token . '/events',
            'media' => $this->pathOrNull('compete_api_media', ['token' => $token]) ?? '/api/compete/' . $token . '/media',
        ];
    }

    /**
     * @param array<string, string> $parameters
     */
    private function pathOrNull(string $route, array $parameters): null|string
    {
        try {
            return $this->generateUrl($route, $parameters);
        } catch (RouteNotFoundException) {
            return null;
        }
    }

    /**
     * The round's public results page - none for a draft or a competition not public yet (it would be a 404).
     */
    private function resultsUrl(OnlineAccessContext $context): null|string
    {
        $competition = $context->competition;
        $round = $context->round;

        if ($round === null || $round->slug === null || $competition->slug === null || $competition->isPubliclyVisible() === false) {
            return null;
        }

        if ($competition->series !== null && $competition->series->slug !== null) {
            return $this->generateUrl('edition_round_results', [
                'seriesSlug' => $competition->series->slug,
                'editionSlug' => $competition->slug,
                'roundSlug' => $round->slug,
            ]);
        }

        return $this->generateUrl('event_round_results', [
            'slug' => $competition->slug,
            'roundSlug' => $round->slug,
        ]);
    }

    /**
     * @return array<string, string>
     */
    private function languageUrls(string $token): array
    {
        $urls = [];

        foreach (self::LOCALES as $locale) {
            $urls[$locale] = $this->generateUrl('compete_page', ['token' => $token, '_locale' => $locale]);
        }

        return $urls;
    }

    /**
     * The page carries the personal token: never stored by any cache, never sent on as a referrer, never indexed
     */
    private static function private(Response $response): Response
    {
        $response->headers->set('Cache-Control', 'no-store, private');
        $response->headers->set('Referrer-Policy', 'same-origin');
        $response->headers->set('X-Robots-Tag', 'noindex');
        // This Cache-Control stands - the session listener must not stamp its own over it for signed-in visitors
        $response->headers->set(AbstractSessionListener::NO_AUTO_CACHE_CONTROL_HEADER, 'true');

        return $response;
    }
}
