<?php

declare(strict_types=1);

namespace SpeedPuzzling\Web\Tests\Navigation;

use SpeedPuzzling\Web\Navigation\NavigationRegistry;
use Symfony\Bundle\FrameworkBundle\Test\KernelTestCase;
use Symfony\Contracts\Translation\TranslatorInterface;

/**
 * The bottom bar's label steps are decided before first paint by the measured table assets/styles/_nav-label-steps.scss
 * (implementation plan NAV-02, decision 95): one entry per locale with its widest label at 11 px and 10 px, measured
 * in the browser by var/navigation-delivery/scripts/checks/NAV-02.py --emit-table. The table records the labels it
 * measured: a changed tab word (a translation, another registry key) fails here until the table is measured again -
 * otherwise CSS would pick the step for the old word and the browser would have to raise it after paint.
 */
final class NavLabelStepsTableTest extends KernelTestCase
{
    private const string TABLE = __DIR__ . '/../../assets/styles/_nav-label-steps.scss';

    private const array LOCALES = ['en', 'cs', 'de', 'es', 'fr', 'ja'];

    // The bar's places in order (PlacesBuilder::ENTRIES)
    private const array PLACE_ENTRIES = ['home', 'puzzles_place', 'add', 'community_place', 'profile'];

    public function testEveryLocaleHasItsMeasuredWidths(): void
    {
        $table = (string) file_get_contents(self::TABLE);

        self::assertStringContainsString('GENERATED by var/navigation-delivery/scripts/checks/NAV-02.py --emit-table', $table);
        self::assertSame(1, preg_match('~\$nav-label-widths: \((.*?)\n\);~s', $table, $map));
        self::assertSame(6, preg_match_all("~'([a-z]{2})': \((\d+(?:\.\d+)?)px, (\d+(?:\.\d+)?)px\),~", $map[1], $rows, PREG_SET_ORDER));

        $locales = [];

        foreach ($rows as [, $locale, $at11, $at10]) {
            $locales[] = $locale;
            // The 10 px width is the 11 px one scaled (the same font, ± hinting)
            self::assertEqualsWithDelta((float) $at11 * 10 / 11, (float) $at10, 0.5, $locale);
            self::assertGreaterThan(20.0, (float) $at11, $locale);
        }

        self::assertSame(self::LOCALES, $locales);

        // The container queries come from the table: both steps for every locale
        self::assertStringContainsString('@container bottom-nav (max-width: #{$step2-below - .01px})', $table);
        self::assertStringContainsString('@container bottom-nav (max-width: #{$step3-below - .01px})', $table);
    }

    public function testTheTableMeasuredTheCurrentTabWords(): void
    {
        self::bootKernel();
        $registry = self::getContainer()->get(NavigationRegistry::class);
        $translator = self::getContainer()->get(TranslatorInterface::class);
        $table = (string) file_get_contents(self::TABLE);

        foreach (self::LOCALES as $locale) {
            $labels = array_map(static function (string $id) use ($registry, $translator, $locale): string {
                $entry = $registry->byId($id);
                self::assertNotNull($entry, $id);

                return $translator->trans($entry->label, [], null, $locale);
            }, self::PLACE_ENTRIES);

            self::assertStringContainsString('//   ' . $locale . ': ' . implode(' · ', $labels) . "\n", $table, sprintf(
                'The %s tab words changed (%s) - measure the table again: python3 var/navigation-delivery/scripts/checks/NAV-02.py --emit-table',
                $locale,
                implode(' · ', $labels),
            ));
        }
    }
}
