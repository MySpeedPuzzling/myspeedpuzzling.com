#!/usr/bin/env python3
"""Export the frame bases from frames/ (f1.py tiers, f1s.py one-off set colours) into bases/ and record them in
bases/bases.json (both committed).

    tools/badge-art/.venv/bin/python -B tools/badge-art/freeze_bases.py                  # first export only
    tools/badge-art/.venv/bin/python -B tools/badge-art/freeze_bases.py --force t5       # deliberately re-freeze t5
    tools/badge-art/.venv/bin/python -B tools/badge-art/freeze_bases.py --force          # re-freeze all

A base = two SVG layers on the 1024 canvas: <stem>-under.svg (drawn before the icon) and <stem>-over.svg (drawn
after it: the T5 crown, the one-off ribbon banner). The build composes under + icon + over and NEVER regenerates a
base: it checks every base file against its sha256 in bases.json and stops if one was edited by hand. Freezing is
deliberate: existing files are only replaced with --force, and only the keys named (default: all). Base files that
no declared base uses any more are deleted. Exit codes: 0 ok, 1 refused (files exist, no --force), 2 bad arguments.
"""
import argparse
import datetime
import hashlib
import json
import os
import sys

os.environ.setdefault("PYTHONDONTWRITEBYTECODE", "1")
sys.dont_write_bytecode = True
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

from frames import BASES, f1  # noqa: E402
from frames.kit import C, OW  # noqa: E402
from lib import paths  # noqa: E402
from lib.compose import ICON_BOX_FIT, layer_text  # noqa: E402


def files_of(key):
    stem = BASES[key][4]
    return {"under": f"{stem}-under.svg", "over": f"{stem}-over.svg"}


def main(argv):
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("keys", nargs="*", help=f"bases to export (default: all of {', '.join(BASES)})")
    ap.add_argument("--force", action="store_true", help="replace existing frozen files")
    a = ap.parse_args(argv)
    unknown = [k for k in a.keys if k not in BASES]
    if unknown:
        print(f"freeze_bases: unknown base {', '.join(unknown)} (known: {', '.join(BASES)})", file=sys.stderr)
        return 2
    paths.check_layout(need_bases=False)
    keys = a.keys or list(BASES)
    decl_path = paths.BASES / "bases.json"
    decl = json.loads(decl_path.read_text()) if decl_path.is_file() else {"bases": {}}
    existing = [paths.BASES / fn for k in keys for fn in files_of(k).values() if (paths.BASES / fn).exists()]
    if existing and not a.force:
        print("freeze_bases: refusing to overwrite frozen bases (use --force to re-freeze deliberately):",
              *[f"  {paths.rel(p)}" for p in existing], sep="\n", file=sys.stderr)
        return 1
    paths.BASES.mkdir(parents=True, exist_ok=True)
    today = datetime.date.today().isoformat()
    for k in keys:
        mk_under, mk_over, status, title, _stem = BASES[k]
        entry = {"title": title, "status": status, "frozen_on": today, "files": files_of(k), "sha256": {}}
        for layer, mk in (("under", mk_under), ("over", mk_over)):
            fn = entry["files"][layer]
            text = layer_text(mk(), f"badge-art frozen base '{k}' {layer}-icon layer: {title}. Generated by "
                                    f"tools/badge-art/freeze_bases.py from frames/ - do not edit by hand.")
            (paths.BASES / fn).write_text(text)
            entry["sha256"][layer] = hashlib.sha256(text.encode()).hexdigest()
            print(f"  {paths.rel(paths.BASES / fn):52s} {len(text) / 1024:7.1f} kB  {status}")
        decl["bases"][k] = entry
    stale = [k for k in decl["bases"] if k not in BASES]
    for k in stale:
        del decl["bases"][k]
        print(f"  dropped base '{k}' (no longer in frames/)")
    used = {fn for k in decl["bases"] for fn in files_of(k).values()}
    for p in sorted(paths.BASES.glob("*.svg")):
        if p.name not in used:
            p.unlink()
            print(f"  deleted {paths.rel(p)} (no declared base uses it)")
    decl.update({
        "frame": "F1 seal ladder v2 (tiers) + F1S-A ribbon seal (one-offs)",
        "generator": "tools/badge-art/freeze_bases.py (frames/)",
        "canvas_px": 1024,
        "outline_px": OW,
        "icon_slot": {"centre_px": [C, C], "bbox_long_side_px": f1.ICON, "fit_radius_px": f1.FIT_R,
                      "plate_radius_px": f1.PLATE, "icon_box_fit": ICON_BOX_FIT},
    })
    decl["bases"] = {k: decl["bases"][k] for k in BASES if k in decl["bases"]}
    order = ["frame", "generator", "canvas_px", "outline_px", "icon_slot", "bases"]
    decl_path.write_text(json.dumps({k: decl[k] for k in order}, indent=1) + "\n")
    print(f"  {paths.rel(decl_path)}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
